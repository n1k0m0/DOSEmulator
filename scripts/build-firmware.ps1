#requires -Version 7.4
[CmdletBinding()]
param()
. (Join-Path $PSScriptRoot 'common.ps1')
$workspaceRoot = Split-Path -Parent $PSScriptRoot
$assembler = Join-Path $workspaceRoot 'artifacts\tools\nasm-3.02\nasm-3.02\nasm.exe'
$sourcePath = Join-Path $workspaceRoot 'firmware\dose-bios.asm'
$generatedPath = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.Image.g.cs'
$firmwareDirectory = Join-Path $workspaceRoot 'firmware'
$identity = [IO.File]::ReadAllText((Join-Path $firmwareDirectory 'bios-identity.inc'))
$biosIdentity = @{}
foreach ($name in @('NAME','VERSION','DATE')) {
    $match = [regex]::Match($identity, ('(?m)^%define BIOS_' + $name + " '([A-Za-z0-9 ._/-]+)'`r?$"))
    if (-not $match.Success) { throw ('Missing or unsafe BIOS identity field: ' + $name) }
    $biosIdentity[$name] = $match.Groups[1].Value
}
# The separately loaded DOS CD-ROM SYS is not a dependency of any system-ROM variant.
$sourceManifest = (Get-ChildItem -LiteralPath $firmwareDirectory -File | Where-Object { $_.Extension -in '.asm','.inc' -and $_.Name -ne 'dose-cdrom.asm' } | Sort-Object Name | ForEach-Object {
    $_.Name + ':' + (Get-DosFileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash
}) -join "`n"
$sourceHash = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($sourceManifest)))
if (-not (Test-Path -LiteralPath $assembler)) {
    $fxGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.FxHost.Image.g.cs'
    $ideGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.PiixIde.Image.g.cs'
    $resetGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.PiixReset.Image.g.cs'
    $trioGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.Trio64.Image.g.cs'
    $pciGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.PciBios.Image.g.cs'
    $winGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.Windows95.Image.g.cs'
    if ((Test-Path -LiteralPath $generatedPath) -and (Get-Content -Raw -LiteralPath $generatedPath).Contains($sourceHash) -and
        (Test-Path -LiteralPath $fxGenerated) -and (Get-Content -Raw -LiteralPath $fxGenerated).Contains($sourceHash) -and
        (Test-Path -LiteralPath $ideGenerated) -and (Get-Content -Raw -LiteralPath $ideGenerated).Contains($sourceHash) -and
        (Test-Path -LiteralPath $resetGenerated) -and (Get-Content -Raw -LiteralPath $resetGenerated).Contains($sourceHash) -and
        (Test-Path -LiteralPath $trioGenerated) -and (Get-Content -Raw -LiteralPath $trioGenerated).Contains($sourceHash) -and
        (Test-Path -LiteralPath $pciGenerated) -and (Get-Content -Raw -LiteralPath $pciGenerated).Contains($sourceHash) -and
        (Test-Path -LiteralPath $winGenerated) -and (Get-Content -Raw -LiteralPath $winGenerated).Contains($sourceHash)) { return }
    throw 'NASM 3.02 is required to rebuild changed firmware. See docs/IMPLEMENTATION-STATUS.md.'
}
$binaryDirectory = Join-Path $workspaceRoot 'artifacts\firmware'
New-Item -ItemType Directory -Path $binaryDirectory -Force | Out-Null
$binaryPath = Join-Path $binaryDirectory 'dose-bios.bin'
& $assembler -Werror -f bin -I ($firmwareDirectory + '\') -o $binaryPath -l (Join-Path $binaryDirectory 'dose-bios.lst') $sourcePath
if ($LASTEXITCODE -ne 0) { throw 'Firmware assembly failed.' }
$bytes = [IO.File]::ReadAllBytes($binaryPath)
if ($bytes.Length -ne 65536) { throw "BIOS must be exactly 65536 bytes, got $($bytes.Length)." }
$memoryStream = [IO.MemoryStream]::new()
$compressor = [IO.Compression.GZipStream]::new($memoryStream,[IO.Compression.CompressionLevel]::Optimal,$true)
$compressor.Write($bytes,0,$bytes.Length)
$compressor.Dispose()
$base64 = [Convert]::ToBase64String($memoryStream.ToArray())
$memoryStream.Dispose()
$code = @"
// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 Nils Kopal
// <auto-generated/> Original dose-bios.asm, Apache-2.0.
namespace DOSEmulator.Runtime;
public static partial class DOSEBios
{
    public const string BiosName = "$($biosIdentity.NAME)";
    public const string BiosVersion = "$($biosIdentity.VERSION)";
    public const string BiosDate = "$($biosIdentity.DATE)";
    public const string SourceSha256 = "$sourceHash";
    private const string CompressedImage = "$base64";
}
"@
if (-not (Test-Path -LiteralPath $generatedPath) -or [IO.File]::ReadAllText($generatedPath) -cne $code) {
    [IO.File]::WriteAllText($generatedPath,$code)
}

# Build the separate host-controller variant; the default ROM byte stream remains unchanged.
$fxBinary = Join-Path $binaryDirectory 'dose-bios-430fx-host.bin'
& $assembler -Werror -f bin -D DOSE_430FX_HOST=1 -I ($firmwareDirectory + '\') -o $fxBinary -l (Join-Path $binaryDirectory 'dose-bios-430fx-host.lst') $sourcePath
if ($LASTEXITCODE -ne 0) { throw '430FX-host firmware assembly failed.' }
$bytes = [IO.File]::ReadAllBytes($fxBinary)
if ($bytes.Length -ne 65536) { throw '430FX-host BIOS must be exactly 65536 bytes.' }
$memoryStream = [IO.MemoryStream]::new()
$compressor = [IO.Compression.GZipStream]::new($memoryStream,[IO.Compression.CompressionLevel]::Optimal,$true)
$compressor.Write($bytes,0,$bytes.Length)
$compressor.Dispose()
$base64 = [Convert]::ToBase64String($memoryStream.ToArray())
$memoryStream.Dispose()
$code = @"
// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 Nils Kopal
// <auto-generated/> Own DOSE_430FX_HOST variant of dose-bios.asm, Apache-2.0.
namespace DOSEmulator.Runtime;
public static partial class DOSEBios
{
    private const string FxHostSourceSha256 = "$sourceHash";
    private const string FxHostCompressedImage = "$base64";
}
"@
$fxGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.FxHost.Image.g.cs'
if (-not (Test-Path -LiteralPath $fxGenerated) -or [IO.File]::ReadAllText($fxGenerated) -cne $code) {
    [IO.File]::WriteAllText($fxGenerated,$code)
}


# Build only the separate IDE board variant with actual guest PCI configuration before POST.
$ideBinary = Join-Path $binaryDirectory 'dose-bios-430fx-piix-ide.bin'
& $assembler -Werror -f bin -D DOSE_430FX_HOST=1 -D DOSE_PIIX_IDE=1 -I ($firmwareDirectory + '\') -o $ideBinary -l (Join-Path $binaryDirectory 'dose-bios-430fx-piix-ide.lst') $sourcePath
if ($LASTEXITCODE -ne 0) { throw '430FX-PIIX-IDE firmware assembly failed.' }
$bytes = [IO.File]::ReadAllBytes($ideBinary)
if ($bytes.Length -ne 65536) { throw '430FX-PIIX-IDE BIOS must be exactly 65536 bytes.' }
$memoryStream = [IO.MemoryStream]::new()
$compressor = [IO.Compression.GZipStream]::new($memoryStream,[IO.Compression.CompressionLevel]::Optimal,$true)
$compressor.Write($bytes,0,$bytes.Length)
$compressor.Dispose()
$base64 = [Convert]::ToBase64String($memoryStream.ToArray())
$memoryStream.Dispose()
$code = @"
// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 Nils Kopal
// <auto-generated/> Own DOSE_PIIX_IDE variant of dose-bios.asm, Apache-2.0.
namespace DOSEmulator.Runtime;
public static partial class DOSEBios
{
    private const string PiixIdeSourceSha256 = "$sourceHash";
    private const string PiixIdeCompressedImage = "$base64";
}
"@
$ideGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.PiixIde.Image.g.cs'
if (-not (Test-Path -LiteralPath $ideGenerated) -or [IO.File]::ReadAllText($ideGenerated) -cne $code) {
    [IO.File]::WriteAllText($ideGenerated,$code)
}


# Build only the separate reset board variant with actual guest PCI configuration before POST.
$resetBinary = Join-Path $binaryDirectory 'dose-bios-430fx-piix-reset.bin'
& $assembler -Werror -f bin -D DOSE_430FX_HOST=1 -D DOSE_PIIX_IDE=1 -D DOSE_PIIX_RESET=1 -I ($firmwareDirectory + '\') -o $resetBinary -l (Join-Path $binaryDirectory 'dose-bios-430fx-piix-reset.lst') $sourcePath
if ($LASTEXITCODE -ne 0) { throw '430FX-PIIX-RESET firmware assembly failed.' }
$bytes = [IO.File]::ReadAllBytes($resetBinary)
if ($bytes.Length -ne 65536) { throw '430FX-PIIX-RESET BIOS must be exactly 65536 bytes.' }
$memoryStream = [IO.MemoryStream]::new()
$compressor = [IO.Compression.GZipStream]::new($memoryStream,[IO.Compression.CompressionLevel]::Optimal,$true)
$compressor.Write($bytes,0,$bytes.Length)
$compressor.Dispose()
$base64 = [Convert]::ToBase64String($memoryStream.ToArray())
$memoryStream.Dispose()
$code = @"
// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 Nils Kopal
// <auto-generated/> Own DOSE_PIIX_RESET variant of dose-bios.asm, Apache-2.0.
namespace DOSEmulator.Runtime;
public static partial class DOSEBios
{
    private const string PiixResetSourceSha256 = "$sourceHash";
    private const string PiixResetCompressedImage = "$base64";
}
"@
$resetGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.PiixReset.Image.g.cs'
if (-not (Test-Path -LiteralPath $resetGenerated) -or [IO.File]::ReadAllText($resetGenerated) -cne $code) {
    [IO.File]::WriteAllText($resetGenerated,$code)
}


# Build only the separate Trio64 PCI board variant with actual guest PCI configuration before POST.
$trioBinary = Join-Path $binaryDirectory 'dose-bios-430fx-piix-s3.bin'
& $assembler -Werror -f bin -D DOSE_430FX_HOST=1 -D DOSE_PIIX_IDE=1 -D DOSE_PIIX_RESET=1 -D DOSE_TRIO64=1 -I ($firmwareDirectory + '\') -o $trioBinary -l (Join-Path $binaryDirectory 'dose-bios-430fx-piix-s3.lst') $sourcePath
if ($LASTEXITCODE -ne 0) { throw '430FX-PIIX-S3 firmware assembly failed.' }
$bytes = [IO.File]::ReadAllBytes($trioBinary)
if ($bytes.Length -ne 65536) { throw '430FX-PIIX-S3 BIOS must be exactly 65536 bytes.' }
$memoryStream = [IO.MemoryStream]::new()
$compressor = [IO.Compression.GZipStream]::new($memoryStream,[IO.Compression.CompressionLevel]::Optimal,$true)
$compressor.Write($bytes,0,$bytes.Length)
$compressor.Dispose()
$base64 = [Convert]::ToBase64String($memoryStream.ToArray())
$memoryStream.Dispose()
$code = @"
// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 Nils Kopal
// <auto-generated/> Own DOSE_TRIO64 variant of dose-bios.asm, Apache-2.0.
namespace DOSEmulator.Runtime;
public static partial class DOSEBios
{
    private const string Trio64SourceSha256 = "$sourceHash";
    private const string Trio64CompressedImage = "$base64";
}
"@
$trioGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.Trio64.Image.g.cs'
if (-not (Test-Path -LiteralPath $trioGenerated) -or [IO.File]::ReadAllText($trioGenerated) -cne $code) {
    [IO.File]::WriteAllText($trioGenerated,$code)
}

# A sixth ROM adds only the selected PCI BIOS/BIOS32 firmware board; prior five byte streams remain independent.
$pciBinary = Join-Path $binaryDirectory 'dose-bios-430fx-piix-s3-atapi-pcibios.bin'
& $assembler -Werror -f bin -D DOSE_430FX_HOST=1 -D DOSE_PIIX_IDE=1 -D DOSE_PIIX_RESET=1 -D DOSE_TRIO64=1 -D DOSE_PCI_BIOS=1 -I ($firmwareDirectory + '\') -o $pciBinary -l (Join-Path $binaryDirectory 'dose-bios-430fx-piix-s3-atapi-pcibios.lst') $sourcePath
if ($LASTEXITCODE -ne 0) { throw 'PCI-BIOS firmware assembly failed.' }
$bytes = [IO.File]::ReadAllBytes($pciBinary)
if ($bytes.Length -ne 65536) { throw 'PCI-BIOS firmware must be exactly 65536 bytes.' }
$directoryMatches = @()
for ($offset = 0; $offset -le $bytes.Length - 16; $offset += 16) {
    if ($bytes[$offset] -eq 0x5f -and $bytes[$offset+1] -eq 0x33 -and $bytes[$offset+2] -eq 0x32 -and $bytes[$offset+3] -eq 0x5f) { $directoryMatches += $offset }
}
if ($directoryMatches.Count -ne 1) { throw 'PCI-BIOS ROM must contain exactly one aligned BIOS32 directory.' }
$directoryOffset = $directoryMatches[0]
$checksum = 0
for ($i = 0; $i -lt 16; $i++) { $checksum += $bytes[$directoryOffset+$i] }
if (($checksum -band 255) -ne 0 -or $bytes[$directoryOffset+8] -ne 0 -or $bytes[$directoryOffset+9] -ne 1) { throw 'Invalid BIOS32 revision, length or checksum.' }
$memoryStream = [IO.MemoryStream]::new()
$compressor = [IO.Compression.GZipStream]::new($memoryStream,[IO.Compression.CompressionLevel]::Optimal,$true)
$compressor.Write($bytes,0,$bytes.Length)
$compressor.Dispose()
$base64 = [Convert]::ToBase64String($memoryStream.ToArray())
$memoryStream.Dispose()
$code = @"
// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 Nils Kopal
// <auto-generated/> Own DOSE_PCI_BIOS firmware variant, Apache-2.0.
namespace DOSEmulator.Runtime;
public static partial class DOSEBios
{
    private const string PciBiosSourceSha256 = "$sourceHash";
    private const string PciBiosCompressedImage = "$base64";
}
"@
$pciGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.PciBios.Image.g.cs'
if (-not (Test-Path -LiteralPath $pciGenerated) -or [IO.File]::ReadAllText($pciGenerated) -cne $code) {
    [IO.File]::WriteAllText($pciGenerated,$code)
}


# A seventh, constructor-selected ROM adds truthful own Trio64 banked VBE1.2/OEM mode effects.
$winBinary = Join-Path $binaryDirectory 'dose-bios-windows95.bin'
& $assembler -Werror -f bin -D DOSE_430FX_HOST=1 -D DOSE_PIIX_IDE=1 -D DOSE_PIIX_RESET=1 -D DOSE_TRIO64=1 -D DOSE_PCI_BIOS=1 -D DOSE_TRIO64_VBE=1 -I ($firmwareDirectory + '\') -o $winBinary -l (Join-Path $binaryDirectory 'dose-bios-windows95.lst') $sourcePath
if ($LASTEXITCODE -ne 0) { throw 'Own Windows95-board VBE firmware assembly failed.' }
$bytes = [IO.File]::ReadAllBytes($winBinary)
if ($bytes.Length -ne 65536) { throw 'Own Windows95-board VBE firmware must be exactly65536 bytes.' }
$winDirectories = @()
for ($offset = 0; $offset -le $bytes.Length - 16; $offset += 16) {
    if ($bytes[$offset] -eq 0x5f -and $bytes[$offset+1] -eq 0x33 -and $bytes[$offset+2] -eq 0x32 -and $bytes[$offset+3] -eq 0x5f) { $winDirectories += $offset }
}
if ($winDirectories.Count -ne 1) { throw 'Own Windows95-board ROM requires exactly one aligned BIOS32 directory.' }
$checksum = 0
for ($i = 0; $i -lt 16; $i++) { $checksum += $bytes[$winDirectories[0]+$i] }
if (($checksum -band 255) -ne 0 -or $bytes[$winDirectories[0]+8] -ne 0 -or $bytes[$winDirectories[0]+9] -ne 1) { throw 'Invalid own Windows95-board BIOS32 directory.' }
$memoryStream = [IO.MemoryStream]::new()
$compressor = [IO.Compression.GZipStream]::new($memoryStream,[IO.Compression.CompressionLevel]::Optimal,$true)
$compressor.Write($bytes,0,$bytes.Length)
$compressor.Dispose()
$base64 = [Convert]::ToBase64String($memoryStream.ToArray())
$memoryStream.Dispose()
$code = @"
// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 Nils Kopal
// <auto-generated/> Own DOSE_TRIO64_VBE firmware variant, Apache-2.0.
namespace DOSEmulator.Runtime;
public static partial class DOSEBios
{
    private const string Windows95SourceSha256 = "$sourceHash";
    private const string Windows95CompressedImage = "$base64";
}
"@
$winGenerated = Join-Path $workspaceRoot 'src\DOSEmulator.Runtime\DOSEBios.Windows95.Image.g.cs'
if (-not (Test-Path -LiteralPath $winGenerated) -or [IO.File]::ReadAllText($winGenerated) -cne $code) {
    [IO.File]::WriteAllText($winGenerated,$code)
}
