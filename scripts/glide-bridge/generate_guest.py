"""Generate a Win9x Glide 2 ABI shim from a local DLL export listing.

The generated code queues common scalar state changes, texture selections,
and bounded vertex lists in caller order. Transfers, queries, and frame
boundaries flush the queue. Other calls use one I/O exit each. The original
DLL is only an ABI reference and is never modified or included in output.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

EXPORT = re.compile(r"^\s*(\d+)\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+(_[A-Za-z0-9_]+@(\d+))\s*$")
PORT = 0xF110
FLOAT_RETURNS = {"_guFogTableIndexToW@4"}
# These Glide 2 state setters return void and have only scalar argument words.
# Their original order is retained inside each batch, which is drained before
# every draw, texture transfer, query, or frame boundary.
BATCHED = {
    "grAlphaBlendFunction", "grAlphaTestFunction", "grAlphaTestReferenceValue",
    "grChromakeyMode", "grChromakeyValue", "grColorCombine", "grColorMask",
    "grConstantColorValue", "grDepthBiasLevel", "grDepthBufferFunction",
    "grDepthBufferMode", "grDepthMask", "grDitherMode", "grFogColorValue",
    "grFogMode", "grHints", "grTexClampMode", "grTexCombine",
    "grTexFilterMode", "grTexMipMapMode", "guAlphaSource",
    "guColorCombineFunction", "guTexCombineFunction",
}


def parse_exports(text: str) -> list[tuple[int, str, int]]:
    """Parse and validate a complete unique Glide 2 ordinal and stdcall export list."""
    exports = [(int(m[1]), m[2], int(m[3])) for line in text.splitlines() if (m := EXPORT.match(line))]
    if len(exports) < 100 or len({row[0] for row in exports}) != len(exports):
        raise ValueError("Expected a complete, unique Glide 2 export table")
    return sorted(exports)


def generate(exports: list[tuple[int, str, int]], destination: Path) -> None:
    """Write the guest transport shim and checked ABI tables from the export list."""
    destination.mkdir(parents=True, exist_ok=True)
    c = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* Generated by scripts/glide-bridge/generate_guest.py. */",
        "/* Original Glide DLL bytes and code are not present in this shim. */",
        '#include "miniglide_splash.h"',
        "typedef unsigned long DWORD;",
        "int __stdcall DllMain(void *module, DWORD reason, void *reserved) {",
        "    (void)module; (void)reason; (void)reserved; return 1;",
        "}",
        "/* Guest-addressable staging for Glide LFB locks. The host fills it on",
        "   read locks and consumes it on write unlocks. */",
        "unsigned char GlideLfbBuffer[4 * 1024 * 1024];",
        "void __stdcall MiniGlideVersion(char *destination) {",
        '    const char version[] = "2.43 MiniGlide 1.0";',
        "    DWORD i;",
        "    for (i = 0; i < 80; ++i) destination[i] = 0;",
        "    for (i = 0; i < sizeof(version); ++i) destination[i] = version[i];",
        "}",
        "/* Scalar Glide state changes are accumulated in caller order. */",
        "static DWORD BridgeBatch[4096];",
        "static DWORD BridgeBatchWords;",
        "void __stdcall BridgeFlush(void) {",
        "    DWORD count = BridgeBatchWords;",
        "    DWORD *data = BridgeBatch;",
        "    if (!count) return;",
        "    __asm {",
        "        push esi",
        "        mov eax, 65534",
        "        mov ecx, data",
        "        mov esi, count",
        f"        mov dx, {PORT}",
        "        out dx, eax",
        "        pop esi",
        "    }",
        "    BridgeBatchWords = 0;",
        "}",
        "void __stdcall BridgeQueue(DWORD id, const DWORD *arguments, DWORD words) {",
        "    DWORD at = BridgeBatchWords;",
        "    if (at + words + 1 > 4096) { BridgeFlush(); at = 0; }",
        "    BridgeBatch[at++] = id;",
        "    for (DWORD i = 0; i < words; i++) BridgeBatch[at++] = arguments[i];",
        "    BridgeBatchWords = at;",
        "}",
        "void __stdcall BridgeQueueTexSource(const DWORD *arguments) {",
        "    DWORD at = BridgeBatchWords;",
        "    if (at + 8 > 4096) { BridgeFlush(); at = 0; }",
        "    BridgeBatch[at++] = 98;",
        "    for (DWORD i = 0; i < 3; i++) BridgeBatch[at++] = arguments[i];",
        "    const DWORD *info = (const DWORD *)arguments[3];",
        "    for (DWORD i = 0; i < 4; i++) BridgeBatch[at++] = info[i];",
        "    BridgeBatchWords = at;",
        "}",
        "/* FxU32 count followed by contiguous 60-byte GrVertex records. Keep",
        "   the caller's data in the ordered batch so a later guest write cannot",
        "   change an earlier draw. Oversized calls use the scalar transport. */",
        "int __stdcall BridgeQueueDraw(DWORD id, const DWORD *arguments) {",
        "    DWORD count = arguments[0];",
        "    if (count == 0 || count > 270) { BridgeFlush(); return 0; }",
        "    DWORD needed = 2 + count * 15;",
        "    DWORD at = BridgeBatchWords;",
        "    if (at + needed > 4096) { BridgeFlush(); at = 0; }",
        "    BridgeBatch[at++] = id;",
        "    BridgeBatch[at++] = count;",
        "    const DWORD *vertices = (const DWORD *)arguments[1];",
        "    for (DWORD i = 0; i < count * 15; i++) BridgeBatch[at++] = vertices[i];",
        "    BridgeBatchWords = at;",
        "    return 1;",
        "}",
        "/* EAX = operation, ECX = pointer to the caller's 32-bit arguments.",
        "   A single OUT enters the host; it replaces EAX with the return bits. */",
    ]
    d = ["LIBRARY GLIDE2X", "EXPORTS"]
    for ordinal, export, stack_bytes in exports:
        symbol = f"bridge_{ordinal}"
        # Branding is local to our DLL, including direct application launches.
        # Keep the original export names and stdcall stack cleanup for ABI compatibility.
        if ordinal in (45, 48, 61):
            body = ["        call BridgeFlush"]
            if ordinal == 45:
                body += ["        push dword ptr [esp+4]", "        call MiniGlideVersion"]
            elif ordinal == 61:
                body += ["        call MiniGlideShowSplash"]
            body += ["        xor eax, eax", f"        ret {stack_bytes}"]
            c.extend([f"__declspec(naked) void __stdcall {symbol}(void) {{",
                      "    __asm {", *body, "    }", "}"])
            d.append(f"    {export} = _{symbol}@0 @{ordinal}")
            continue
        lfb_lock = export == "_grLfbLock@24"
        tex_source = export == "_grTexSource@16"
        draw_list = ordinal in (34, 37)
        batched = export[1:].split("@")[0] in BATCHED or tex_source
        c.extend([
            f"__declspec(naked) void __stdcall {symbol}(void) {{",
            "    __asm {",
            *([] if batched or draw_list else ["        call BridgeFlush"]),
            *(["        call MiniGlideShowSplash"] if ordinal == 46 else []),
            *(["        push esi", "        mov esi, offset GlideLfbBuffer"] if lfb_lock else []),
            f"        mov eax, {ordinal}",
            "        lea ecx, [esp+8]" if lfb_lock else "        lea ecx, [esp+4]",
            *(["        push ecx", "        push eax", "        call BridgeQueueDraw",
               "        test eax, eax", f"        jnz queued_{ordinal}",
               f"        mov eax, {ordinal}", "        lea ecx, [esp+4]",
               f"        mov dx, {PORT}", "        out dx, eax",
               f"    queued_{ordinal}:"] if draw_list else
              ["        push ecx", "        call BridgeQueueTexSource"] if tex_source else
              [f"        push {stack_bytes // 4}", "        push ecx", "        push eax", "        call BridgeQueue"]
              if batched else [f"        mov dx, {PORT}", "        out dx, eax"]),
            *(["        pop esi"] if lfb_lock else []),
            *(["        push eax", "        fld dword ptr [esp]", "        add esp, 4"] if export in FLOAT_RETURNS else []),
            f"        ret {stack_bytes}",
            "    }",
            "}",
        ])
        d.append(f"    {export} = _{symbol}@0 @{ordinal}")
    (destination / "glide2x_bridge.c").write_text("\n".join(c) + "\n", encoding="ascii")
    (destination / "glide2x_bridge.def").write_text("\n".join(d) + "\n", encoding="ascii")
    (destination / "exports.csv").write_text(
        "ordinal,name,stack_bytes\n" + "".join(f"{n},{name},{size}\n" for n, name, size in exports), encoding="ascii"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("dumpbin_listing", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    generate(parse_exports(args.dumpbin_listing.read_text(encoding="utf-8")), args.destination)
